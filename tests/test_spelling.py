"""표기 흔들림 교정 검사.

**여기서 지키는 것은 "잡는다" 가 아니라 "잘못 잡지 않는다" 이다.**
교정은 추정이고, 추정이 안전 판정으로 이어지면 회복되지 않는다.
그래서 오탐 차단 검사가 정탐 검사보다 많다.
"""

from __future__ import annotations

import pytest

from pettriage.compute.spelling import (
    Correction,
    correct,
    edit_distance,
    normalize,
)

#: 실제 어휘의 일부. 오탐 검사에 필요한 것들을 일부러 함께 넣었다 —
#: `포도`·`사과` 는 2글자 함정, `케이블`·`바나나`·`개박하` 는 첫 글자 함정이다.
어휘 = [
    "초콜릿",
    "포도",
    "사과",
    "바나나",
    "고구마",
    "개박하",
    "몬스테라",
    "마카다미아",
    "자일리톨",
    "케이블",
    "알리움류",
    "벚나무속 과일 씨",
]


# ── 정규화 ──────────────────────────────────────────────────


@pytest.mark.parametrize(
    ("입력", "기대"),
    [
        ("체리 씨", "체리씨"),
        ("체리씨앗", "체리씨앗"),
        ("무설탕 껌", "무설탕껌"),
        ("Choco-Late", "chocolate"),
        ("  포도  ", "포도"),
    ],
)
def test_정규화가_공백과_기호를_지운다(입력: str, 기대: str) -> None:
    assert normalize(입력) == 기대


def test_띄어쓰기만_다르면_거리가_0이다() -> None:
    """aliases.py §④ 가 부채로 지목한 것 — 표를 4행으로 늘릴 이유가 없다."""
    assert edit_distance(normalize("체리 씨"), normalize("체리씨")) == 0


# ── 정탐 ───────────────────────────────────────────────────


@pytest.mark.parametrize(
    ("입력", "기대"),
    [
        ("초콜렛", "초콜릿"),  # 실측으로 refused 를 냈던 그 입력
        ("초코릿", "초콜릿"),
        ("몬스테나", "몬스테라"),
        ("고구가", "고구마"),
        ("마카다미어", "마카다미아"),
    ],
)
def test_한_글자_흔들림을_교정한다(입력: str, 기대: str) -> None:
    결과 = correct(입력, 어휘)
    assert 결과 is not None, f"{입력} 이 교정되지 않았다"
    assert 결과.name == 기대
    assert 결과.surface == 입력  # 보호자가 쓴 말을 잃지 않는다


def test_정확히_같으면_거리가_0으로_교정된다() -> None:
    """이미 아는 말은 애초에 여기까지 오지 않지만, 와도 자기 자신을 낸다."""
    결과 = correct("초콜릿", 어휘)
    assert 결과 == Correction(surface="초콜릿", name="초콜릿", distance=0)


# ── 오탐 차단 — 이 검사들이 이 모듈의 존재 이유다 ────────────────


@pytest.mark.parametrize(
    ("입력", "막는_규칙"),
    [
        ("포토", "2글자는 교정하지 않는다 (→포도 였다)"),
        ("사고", "2글자는 교정하지 않는다 (→사과 였다)"),
        ("양말", "2글자는 교정하지 않는다"),
    ],
)
def test_짧은_말은_교정하지_않는다(입력: str, 막는_규칙: str) -> None:
    assert correct(입력, 어휘) is None, 막는_규칙


@pytest.mark.parametrize(
    ("입력", "막는_규칙"),
    [
        ("테이블", "첫 글자가 다르다 (→케이블 이었다)"),
        ("하나나", "첫 글자가 다르다 (→바나나 였다)"),
        ("내박하", "첫 글자가 다르다 (→개박하 였다)"),
    ],
)
def test_첫_글자가_다르면_교정하지_않는다(입력: str, 막는_규칙: str) -> None:
    assert correct(입력, 어휘) is None, 막는_규칙


@pytest.mark.parametrize(
    ("입력", "설명"),
    [
        ("초코레또", "거리 3"),
        ("몬스테리아", "거리 2 — `리` 교체 + `아` 삽입. 잡으려면 별칭 표에 넣어야 한다"),
        ("산세비에리아", "거리 2 — 같은 이유"),
    ],
)
def test_두_글자_이상_다르면_교정하지_않는다(입력: str, 설명: str) -> None:
    """**이것이 이 모듈의 한계다.**

    임계를 2 로 올리면 잡히지만 `사과`↔`사고` 급 오탐이 함께 늘어난다.
    이런 것은 계산이 아니라 별칭 표 한 행으로 처리하는 편이 싸고 예측 가능하다.
    """
    assert correct(입력, 어휘) is None, 설명


def test_동점이면_교정하지_않고_유보한다() -> None:
    """어느 쪽인지 계산으로 못 가린다. 하나를 고르면 틀릴 확률을 몰래 떠넘긴다."""
    동점_어휘 = ["사료캔", "사료캡"]
    assert correct("사료캇", 동점_어휘) is None


def test_아무_관계없는_말은_교정하지_않는다() -> None:
    assert correct("산책했어요", 어휘) is None
    assert correct("아무거나", 어휘) is None


# ── 거리 계산 ────────────────────────────────────────────────


@pytest.mark.parametrize(
    ("a", "b", "기대"),
    [
        ("초콜렛", "초콜릿", 1),
        ("초콜릿", "초콜릿", 0),
        ("고구가", "고구마", 1),
    ],
)
def test_편집거리(a: str, b: str, 기대: int) -> None:
    assert edit_distance(a, b) == 기대


def test_임계를_넘으면_정확한_값_대신_초과_표시를_낸다() -> None:
    """호출자는 초과 여부만 본다. 정확한 거리를 계산할 이유가 없다."""
    assert edit_distance("초콜렛", "포도") > 1
    assert edit_distance("완전히다른말", "초콜릿") > 1
